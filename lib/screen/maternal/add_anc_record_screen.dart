import 'package:flutter/material.dart';

import '../../models/maternal_anc_model.dart';
import '../../services/maternal_child_repository.dart';

class AddAncRecordScreen extends StatefulWidget {
  final String pregnancyId;

  const AddAncRecordScreen({super.key, required this.pregnancyId});

  @override
  State<AddAncRecordScreen> createState() => _AddAncRecordScreenState();
}

class _AddAncRecordScreenState extends State<AddAncRecordScreen> {
  final _formKey = GlobalKey<FormState>();
  final _repository = MaternalChildRepository();

  int _trimester = 1;
  int? _gestationalWeeks;
  double? _weightKg;
  String? _bloodPressure;
  double? _hbLevel;
  double? _fundalHeight;
  int? _fetalHeartRate;
  String? _complaints;
  int? _ttdTablets;
  String? _counselingNotes;
  String? _providerName;
  final DateTime _visitDate = DateTime.now();

  bool _isLoading = false;

  Future<void> _submitData() async {
    if (_formKey.currentState!.validate()) {
      _formKey.currentState!.save();
      setState(() => _isLoading = true);

      try {
        final newRecord = MaternalAncModel(
          id: '', // Generated by Supabase/DB if default
          pregnancyId: widget.pregnancyId,
          visitDate: _visitDate,
          trimester: _trimester,
          gestationalAgeWeeks: _gestationalWeeks,
          weightKg: _weightKg,
          bloodPressure: _bloodPressure,
          hbLevel: _hbLevel,
          fundalHeightCm: _fundalHeight,
          fetalHeartRate: _fetalHeartRate,
          complaints: _complaints,
          ttdTabletsGiven: _ttdTablets,
          counselingNotes: _counselingNotes,
          healthcareProviderName: _providerName,
          createdAt: DateTime.now(),
        );

        await _repository.addAncRecord(newRecord);
        if (!mounted) return;
        Navigator.pop(context, true);
      } catch (e) {
        if (!mounted) return;
        ScaffoldMessenger.of(context)
            .showSnackBar(SnackBar(content: Text('Gagal menyimpan data: $e')));
      } finally {
        if (mounted) setState(() => _isLoading = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text('Tambah Pemeriksaan ANC')),
      body: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Form(
          key: _formKey,
          child: ListView(
            children: [
              // Trimester Dropdown
              DropdownButtonFormField<int>(
                initialValue: _trimester,
                decoration: InputDecoration(labelText: 'Trimester Kehamilan'),
                items: [1, 2, 3].map((t) {
                  return DropdownMenuItem(
                    value: t,
                    child: Text('Trimester $t'),
                  );
                }).toList(),
                onChanged: (val) => setState(() => _trimester = val ?? 1),
              ),
              TextFormField(
                decoration: InputDecoration(
                  labelText: 'Usia Kehamilan (Minggu)',
                ),
                keyboardType: TextInputType.number,
                onSaved: (val) => _gestationalWeeks = int.tryParse(val ?? ''),
              ),
              TextFormField(
                decoration: InputDecoration(labelText: 'Berat Badan Ibu (kg)'),
                keyboardType: TextInputType.number,
                onSaved: (val) => _weightKg = double.tryParse(val ?? ''),
              ),
              TextFormField(
                decoration: InputDecoration(
                  labelText: 'Tekanan Darah (Contoh: 120/80)',
                ),
                onSaved: (val) => _bloodPressure = val,
              ),
              TextFormField(
                decoration: InputDecoration(labelText: 'Kadar Hb (g/dL)'),
                keyboardType: TextInputType.number,
                onSaved: (val) => _hbLevel = double.tryParse(val ?? ''),
              ),
              TextFormField(
                decoration: InputDecoration(
                  labelText: 'Jumlah Tablet Tambah Darah (TTD) Diterima',
                ),
                keyboardType: TextInputType.number,
                onSaved: (val) => _ttdTablets = int.tryParse(val ?? ''),
              ),
              TextFormField(
                decoration: InputDecoration(labelText: 'Keluhan Utama'),
                maxLines: 2,
                onSaved: (val) => _complaints = val,
              ),
              TextFormField(
                decoration: InputDecoration(
                  labelText: 'Nama Pemberi Pelayanan / Faskes',
                ),
                onSaved: (val) => _providerName = val,
              ),
              SizedBox(height: 24),
              ElevatedButton(
                onPressed: _isLoading ? null : _submitData,
                child: _isLoading
                    ? CircularProgressIndicator(color: Colors.white)
                    : Text('Simpan Pemeriksaan ANC'),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
